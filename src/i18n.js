let atual = 'pt';

export function detectarIdioma(env = process.env, sistema = Intl.DateTimeFormat().resolvedOptions().locale) {
  return /^pt/i.test(env.NES_IDIOMA || env.LC_ALL || env.LC_MESSAGES || env.LANG || sistema) ? 'pt' : 'en';
}

